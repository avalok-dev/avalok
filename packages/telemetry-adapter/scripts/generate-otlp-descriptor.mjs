#!/usr/bin/env node
// Generates `src/otlp-proto-descriptor.ts` from the vendored official `.proto` definitions.
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";
import protobuf from "protobufjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function loadOtlpDescriptor() {
  const root = new protobuf.Root();
  root.resolvePath = (_origin, target) =>
    target.startsWith("google/protobuf/") ? target : join(packageRoot, "proto", target);
  root.loadSync(
    ["opentelemetry/proto/collector/trace/v1/trace_service.proto", "google/rpc/status.proto"],
    { keepCase: false },
  );
  return root.toJSON();
}

if (process.argv[1] && import.meta.url === `file://${resolve(process.argv[1])}`) {
  const source = `// Generated by scripts/generate-otlp-descriptor.mjs from proto/ (opentelemetry-proto v1.11.0).
// Do not edit by hand.
export const otlpTraceDescriptor = ${JSON.stringify(loadOtlpDescriptor(), null, 2)};
`;
  writeFileSync(join(packageRoot, "src", "otlp-proto-descriptor.ts"), source);
}
